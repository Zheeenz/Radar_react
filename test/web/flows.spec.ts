import { test, expect } from '@playwright/test';

test.beforeEach(async ({ request }) => { await request.post('/api/reset', { data: {} }); });

test('desktop: explore, favorites, ingredients, barcode and shopping persist', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/explore');
  await expect(page.getByText('Tu próximo paradero,')).toBeVisible();
  await page.getByPlaceholder('Busca lugares, productos o ingredientes').fill('tofu');
  await expect(page.getByText(/lugares encontrados/)).toBeVisible();
  await page.getByPlaceholder('Busca lugares, productos o ingredientes').fill('');
  await page.getByRole('button', { name: 'Guardar Café Brote en favoritos', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Quitar Café Brote de favoritos', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Mis favoritos', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Ver Café Brote', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Verificador', exact: true }).click();
  await page.getByRole('textbox', { name: 'Ingredientes de la etiqueta' }).fill('Agua, avena, leche de coco, sal');
  await page.getByRole('button', { name: 'Revisar ingredientes', exact: true }).click();
  await expect(page.getByText('Compatible según ingredientes', { exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Ingredientes de la etiqueta' }).fill('Leche, azúcar, cacao');
  await page.getByRole('button', { name: 'Revisar ingredientes', exact: true }).click();
  await expect(page.getByText('Contiene ingredientes animales', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Código de barras', exact: true }).click();
  await page.getByRole('textbox', { name: 'Código de barras', exact: true }).fill('7800000000011');
  await page.getByRole('button', { name: 'Buscar producto', exact: true }).click();
  await expect(page.getByText('Producto encontrado en el catálogo.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Añadir a mi lista', exact: true }).click();
  await page.getByRole('button', { name: /^Lista de compras/ }).click();
  await expect(page.getByText('Mi lista de compras', { exact: true })).toBeVisible();
  await expect(page.getByRole('checkbox').first()).toBeVisible();
  await page.reload();
  await expect(page.getByRole('checkbox').first()).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar lista', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('paradero-lista-compras.csv');
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'docs/capturas/compras-web.png', fullPage: true });
});

test('desktop: map, evidence, premium recipes and commerce panel', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/explore');
  await expect(page.getByText('Tu próximo paradero,')).toBeVisible();
  await page.screenshot({ path: 'docs/capturas/explorar-web.png', fullPage: true });
  await page.getByRole('button', { name: 'Mapa', exact: true }).click();
  await expect(page.getByLabel('Mapa de lugares de Santiago')).toBeVisible();
  await expect(page.locator('.leaflet-interactive')).toHaveCount(8);
  await page.getByRole('button', { name: 'Compartir evidencia', exact: true }).first().click();
  await page.getByRole('textbox', { name: 'Título del aporte' }).fill('Etiqueta revisada en la migración');
  await page.getByRole('textbox', { name: 'Ingredientes o detalles de la etiqueta' }).fill('Agua, avena, sal');
  await page.getByRole('button', { name: 'Guardar aporte', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Guardar aporte', exact: true })).not.toBeVisible();
  await page.goto('/plans');
  await page.getByRole('button', { name: 'Probar este plan', exact: true }).last().click();
  await expect(page.getByText('Plan de prueba activado. No se realizó ningún cobro.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Mi comercio', exact: true }).click();
  await expect(page.getByText('Actividad de los últimos 7 días', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '30 días', exact: true }).click();
  await expect(page.getByText('542', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'docs/capturas/comercio-web.png', fullPage: true });
  await page.getByRole('button', { name: 'Recetario', exact: true }).click();
  await page.getByRole('button', { name: 'Vamos a cocinar', exact: true }).first().click();
  await expect(page.getByRole('button', { name: 'Añadir productos a mi lista', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('mobile web: bottom navigation, menu, profile and no horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/explore');
  await expect(page.getByText('Tu próximo paradero,')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Abrir menú', exact: true })).toBeVisible();
  await page.screenshot({ path: 'docs/capturas/explorar-movil.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Abrir menú', exact: true }).click();
  await page.getByRole('button', { name: 'Mi perfil y preferencias', exact: true }).click();
  await page.getByRole('textbox', { name: 'Tu nombre', exact: true }).fill('Catalina');
  await page.getByRole('checkbox', { name: 'Económico', exact: true }).check();
  await page.getByRole('button', { name: 'Guardar mis preferencias', exact: true }).click();
  await expect(page.getByText('Preferencias guardadas', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('textbox', { name: 'Tu nombre', exact: true })).toHaveValue('Catalina');
  await expect(page.getByRole('checkbox', { name: 'Económico', exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'Verificador', exact: true }).click();
  await expect(page.getByText('¿Qué hay en tu etiqueta?', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
